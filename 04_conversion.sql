-- Вопрос (запрос маркетинга): в каком городе зарегистрированные пользователи хуже всего превращаются в покупателей?
-- Конверсия в покупку = пользователи с хотя бы одним оплаченным заказом / все зарегистрированные * 100.
-- Приём: LEFT JOIN (не теряем тех, кто не купил), фильтр paid в ON (не в WHERE),
--        COUNT(DISTINCT u.user_id) = все люди, COUNT(DISTINCT o.user_id) = только платившие (у остальных NULL).
SELECT u.city, COUNT(DISTINCT u.user_id) AS users_cnt, COUNT(DISTINCT o.user_id) AS buyers_cnt,
ROUND(100.0 * COUNT(DISTINCT o.user_id) / COUNT(DISTINCT u.user_id), 1) AS conversion_pct
FROM users u 
LEFT JOIN orders o ON o.user_id = u.user_id AND o.status = 'paid'
GROUP BY u.city
ORDER BY conversion_pct DESC;

